// escapeCell applies the escaping rules for a markdown table cell:
// pipe characters become \|, and newlines become <br>.
func escapeCell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.ReplaceAll(s, "\n", "<br>")
	return strings.TrimSpace(s)
}

// renderItemStatus renders the status cell value from structured fields.
func renderItemStatus(it Item) string {
	switch it.Status {
	case StatusDone:
		for _, pr := range it.PRs {
			if pr.Role == RoleCompleting {
				return fmt.Sprintf("DONE — PR #%d", pr.Num)
			}
		}
		return "DONE"
	case StatusWontfix:
		return "WONTFIX"
	case StatusBlocked:
		return fmt.Sprintf("BLOCKED:%s", it.Blocker)
	default:
		return string(it.Status)
	}
}

// renderQuestionStatus renders the status cell value for a question.
func renderQuestionStatus(q Question) string {
	switch q.Status {
	case StatusDone:
		for _, pr := range q.PRs {
			if pr.Role == RoleCompleting {
				return fmt.Sprintf("DONE — PR #%d", pr.Num)
			}
		}
		return "DONE"
	case StatusWontfix:
		return "WONTFIX"
	case StatusBlocked:
		return fmt.Sprintf("BLOCKED:%s", q.Blocker)
	default:
		return string(q.Status)
	}
}

// renderItemRefs renders a refs list as a comma-separated string.
func renderItemRefs(refs []string) string {
	return strings.Join(refs, ", ")
}

// sortedItems returns items in canonical typed sort order.
func sortedItems(items []Item) []Item {
	out := make([]Item, len(items))
	copy(out, items)
	sort.SliceStable(out, func(i, j int) bool {
		ki := parseItemSortKey(out[i].ID)
		kj := parseItemSortKey(out[j].ID)
		return ki.less(kj)
	})
	return out
}

// sortedQuestions returns questions in canonical typed sort order (q<N>[letter]).
func sortedQuestions(qs []Question) []Question {
	out := make([]Question, len(qs))
	copy(out, qs)
	sort.SliceStable(out, func(i, j int) bool {
		ki := parseQSortKey(out[i].ID)
		kj := parseQSortKey(out[j].ID)
		return ki.less(kj)
	})
	return out
}

func parseQSortKey(id string) sortKey {
	rest := id[1:] // strip 'q'
	k := strings.IndexFunc(rest, func(r rune) bool { return r < '0' || r > '9' })
	if k == -1 {
		n, _ := parseInt(rest)
		return sortKey{n: n, brickN: -1}
	}
	n, _ := parseInt(rest[:k])
	return sortKey{n: n, letter: rest[k:], brickN: -1}
}

func parseInt(s string) (int, error) {
	n := 0
	for _, c := range s {
		if c < '0' || c > '9' {
			return 0, fmt.Errorf("not an integer: %q", s)
		}
		n = n*10 + int(c-'0')
	}
	return n, nil
}

// genItemsOpenClosed writes the open and closed item registry tables to their
// respective writers.  Phase 1: writes to any io.Writer (typically a buffer).
func genItemsOpenClosed(reg *Registry, openW, closedW io.Writer) error {
	items := sortedItems(reg.Items)

	header := "| **id** | title | status | refs |\n|---|---|---|---|\n"

	// Open items.
	fmt.Fprint(openW, generatedBannerItems)
	fmt.Fprint(openW, "\n")
	fmt.Fprint(openW, header)
	for _, it := range items {
		if isOpen(it.Status) {
			fmt.Fprintf(openW, "| **%s** | %s | %s | %s |\n",
				escapeCell(it.ID),
				escapeCell(it.Title),
				escapeCell(renderItemStatus(it)),
				escapeCell(renderItemRefs(it.Refs)),
			)
		}
	}

	// Closed items.
	fmt.Fprint(closedW, generatedBannerItems)
	fmt.Fprint(closedW, "\n")
	fmt.Fprint(closedW, header)
	for _, it := range items {
		if !isOpen(it.Status) {
			fmt.Fprintf(closedW, "| **%s** | %s | %s | %s |\n",
				escapeCell(it.ID),
				escapeCell(it.Title),
				escapeCell(renderItemStatus(it)),
				escapeCell(renderItemRefs(it.Refs)),
			)
		}
	}
	return nil
}

