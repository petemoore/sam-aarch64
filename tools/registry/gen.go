// escapeCell applies the escaping rules for a markdown table cell:
// pipe characters become \|, and newlines become <br>.
// Escaping happens in one place (spec §"Generator").
func escapeCell(s string) string {
	// Trim first, so a block scalar's trailing newline doesn't become a spurious
	// trailing <br>; internal newlines (real line breaks) still render as <br>.
	s = strings.TrimSpace(s)
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.ReplaceAll(s, "\n", "<br>")
	return s
}

// repoPullURL is the base URL for pull requests in this repository.
const repoPullURL = "https://github.com/petemoore/sam-aarch64/pull/"

// renderItemStatus renders the status cell — just the status token.
// PR information is rendered separately in the PR column.
// No BLOCKED rendering — blocked-ness is derived from depends_on edges, not stored.
func renderItemStatus(it Item) string {
	return string(it.Status)
}

// renderItemPRs renders the PR column as comma-separated clickable markdown links,
// e.g. "[#124](https://github.com/petemoore/sam-aarch64/pull/124)".
// Returns an empty string when the item carries no PRs.
// The returned string is already safe markdown — do NOT run escapeCell over it.
func renderItemPRs(it Item) string {
	if len(it.PRs) == 0 {
		return ""
	}
	parts := make([]string, 0, len(it.PRs))
	for _, pr := range it.PRs {
		parts = append(parts, fmt.Sprintf("[#%d](%s%d)", pr.Num, repoPullURL, pr.Num))
	}
	return strings.Join(parts, ", ")
}

// renderItemDependents renders the reverse-dependency column: ids of all items
// whose depends_on includes this item's id, in canonical sort order.
// Returns an empty string when no items depend on this item.
func renderItemDependents(it Item, reverseEdges map[string][]string) string {
	dependents := reverseEdges[it.ID]
	if len(dependents) == 0 {
		return ""
	}
	// Return a copy in sorted order (reverseEdges is pre-sorted at build time).
	return strings.Join(dependents, ", ")
}

// buildReverseEdges returns a map from item id to the sorted list of ids of all
// items that declare depends_on including that id.
func buildReverseEdges(items []Item) map[string][]string {
	rev := map[string][]string{}
	for _, it := range items {
		for _, dep := range it.DependsOn {
			rev[dep] = append(rev[dep], it.ID)
		}
	}
	// Sort each list for deterministic output.
	for k := range rev {
		sortStrings(rev[k])
	}
	return rev
}

// renderItemDeps renders the depends_on edges — the gating item/question ids
// that make up the dependency DAG. It is its own first-class column so the DAG
// is readable from the generated view, not buried among cross-links. Empty when
// the item is not gated on anything.
func renderItemDeps(it Item) string {
	return strings.Join(it.DependsOn, ", ")
}

// renderItemRefs renders the cross-links / pointers (file paths, §sections, URLs,
// related ids). It EXCLUDES any ref id that is also a depends_on target — those
// belong to the deps column, so an id is never shown twice.
func renderItemRefs(it Item) string {
	dep := make(map[string]bool, len(it.DependsOn))
	for _, d := range it.DependsOn {
		dep[d] = true
	}
	parts := make([]string, 0, len(it.Refs))
	for _, r := range it.Refs {
		if !dep[r] {
			parts = append(parts, r)
		}
	}
	return strings.Join(parts, ", ")
}

// renderIDCell renders the leading id cell with an in-file anchor target (i159):
// an empty `<a id="iNN"></a>` before the bold id, so a `[iNN](#iNN)` link
// elsewhere in the SAME doc jumps to this row. GitHub prefixes both the anchor id
// and same-page fragment links with `user-content-`, keeping them consistent; the
// anchor is invisible, so the cell still displays just the bold id. The id matches
// itemIDRe/questionIDRe (safe as an HTML attribute / fragment).
func renderIDCell(id string) string {
	return `<a id="` + id + `"></a>**` + id + "**"
}

// linkifyIDList rewrites a ", "-joined cell (deps / dependents / refs) so every
// token that is the id of a row IN THIS SAME VIEW becomes an in-file anchor link
// `[id](#id)` (i159). Gating on presentInView keeps the links in-file: a token is
// linked only when its row exists in this doc, so cross-doc ids (a closed dep seen
// from the open view, a qN seen from an item view) and non-id ref tokens (file
// paths, URLs, §sections — never equal to a present id) pass through unchanged, so
// no link ever dangles. Operates on the already-escaped cell text; the link syntax
// it emits contains no characters escapeCell would touch.
func linkifyIDList(s string, presentInView map[string]bool) string {
	if s == "" {
		return s
	}
	parts := strings.Split(s, ", ")
	for i, p := range parts {
		if presentInView[p] {
			parts[i] = "[" + p + "](#" + p + ")"
		}
	}
	return strings.Join(parts, ", ")
}

// presentIDs returns the set of ids that have a data row in a view, for
// linkifyIDList's in-file gating.
func presentIDs(ids []string) map[string]bool {
	m := make(map[string]bool, len(ids))
	for _, id := range ids {
		m[id] = true
	}
	return m
}

// sortedItems returns items in canonical typed sort order.
func sortedItems(items []Item) []Item {
	out := make([]Item, len(items))
	copy(out, items)
	sort.SliceStable(out, func(i, j int) bool {
		ki := parseItemSortKey(out[i].ID)
		kj := parseItemSortKey(out[j].ID)
		return ki.less(kj)
	})
	return out
}

// sortedQuestions returns questions in canonical typed sort order (q<N>[letter]).
func sortedQuestions(qs []Question) []Question {
	out := make([]Question, len(qs))
	copy(out, qs)
	sort.SliceStable(out, func(i, j int) bool {
		ki := parseQSortKey(out[i].ID)
		kj := parseQSortKey(out[j].ID)
		return ki.less(kj)
	})
	return out
}

func parseQSortKey(id string) sortKey {
	rest := id[1:] // strip 'q'
	k := strings.IndexFunc(rest, func(r rune) bool { return r < '0' || r > '9' })
	if k == -1 {
		n, _ := parseInt(rest)
		return sortKey{n: n, brickN: -1}
	}
	n, _ := parseInt(rest[:k])
	return sortKey{n: n, letter: rest[k:], brickN: -1}
}

func parseInt(s string) (int, error) {
	n := 0
	for _, c := range s {
		if c < '0' || c > '9' {
			return 0, fmt.Errorf("not an integer: %q", s)
		}
		n = n*10 + int(c-'0')
	}
	return n, nil
}

// renderItemCell renders the item's display cell: the bold title followed by the
// description, so the generated table carries the item's actual content (not just
// the short title) — mirroring how questions render their full body. The old
// hand-edited registry's "item" column was exactly this: a bold lead-in + detail.
func renderItemCell(it Item) string {
	title := escapeCell(it.Title)
	desc := escapeCell(it.Description)
	if desc == "" {
		return "**" + title + "**"
	}
	return "**" + title + "** — " + desc
}

// genItemsOpenClosed writes the open and closed item registry tables to their
// respective writers. Spec §"Generator" — three views total (two item + one question).
// The OPEN view carries a "gate" column (mirroring backlog.md's computeGates, i158)
// so the open-items table shows at a glance what is actionable vs blocked-on-Pete
// vs blocked-on-work — the same marker the backlog uses. The CLOSED view omits it:
// every closed item is DONE/WONTFIX, so a deps-derived gate would be meaningless.
// Open column order:   id | item | status | owner | gate | PR | deps | dependents | refs/links
// Closed column order: id | item | status | owner | PR | deps | dependents | refs/links
func genItemsOpenClosed(reg *Registry, openW, closedW io.Writer) error {
	items := sortedItems(reg.Items)
	reverseEdges := buildReverseEdges(items)
	gates := computeGates(reg)

	// In-file anchor targets (i159): the open view links only to ids whose row is
	// in the open view, the closed view only to closed ids — so a linkified ref
	// never points at a row that lives in the other file.
	var openIDs, closedIDs []string
	for _, it := range items {
		if isOpen(it.Status) {
			openIDs = append(openIDs, it.ID)
		} else {
			closedIDs = append(closedIDs, it.ID)
		}
	}
	openPresent := presentIDs(openIDs)
	closedPresent := presentIDs(closedIDs)

	openHeader := "| **id** | item | status | owner | gate | PR | deps | dependents | refs/links |\n|---|---|---|---|---|---|---|---|---|\n"
	closedHeader := "| **id** | item | status | owner | PR | deps | dependents | refs/links |\n|---|---|---|---|---|---|---|---|\n"

	// Open items (OPEN or IN_PROGRESS) — with the gate column.
	fmt.Fprint(openW, generatedBannerItems)
	fmt.Fprint(openW, "\n")
	fmt.Fprint(openW, openHeader)
	for _, it := range items {
		if isOpen(it.Status) {
			fmt.Fprintf(openW, "| %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
				renderIDCell(it.ID),
				renderItemCell(it),
				escapeCell(renderItemStatus(it)),
				escapeCell(it.Owner),
				escapeCell(gates[it.ID]),
				renderItemPRs(it),
				linkifyIDList(escapeCell(renderItemDeps(it)), openPresent),
				linkifyIDList(escapeCell(renderItemDependents(it, reverseEdges)), openPresent),
				linkifyIDList(escapeCell(renderItemRefs(it)), openPresent),
			)
		}
	}

	// Closed items (DONE or WONTFIX) — no gate column.
	fmt.Fprint(closedW, generatedBannerItems)
	fmt.Fprint(closedW, "\n")
	fmt.Fprint(closedW, closedHeader)
	for _, it := range items {
		if !isOpen(it.Status) {
			fmt.Fprintf(closedW, "| %s | %s | %s | %s | %s | %s | %s | %s |\n",
				renderIDCell(it.ID),
				renderItemCell(it),
				escapeCell(renderItemStatus(it)),
				escapeCell(it.Owner),
				renderItemPRs(it),
				linkifyIDList(escapeCell(renderItemDeps(it)), closedPresent),
				linkifyIDList(escapeCell(renderItemDependents(it, reverseEdges)), closedPresent),
				linkifyIDList(escapeCell(renderItemRefs(it)), closedPresent),
			)
		}
	}
	return nil
}

// genQuestionsOpen writes the open question registry table to the given writer.
// Questions are transient (spec §"Questions — transient by design"):
// there is ONE generated view — open only; no closed view.
func genQuestionsOpen(reg *Registry, openW io.Writer) error {
	questions := sortedQuestions(reg.Questions)

	header := "| **id** | body | owner |\n|---|---|---|\n"

	fmt.Fprint(openW, generatedBannerQuestions)
	fmt.Fprint(openW, "\n")
	fmt.Fprint(openW, header)
	for _, q := range questions {
		fmt.Fprintf(openW, "| **%s** | %s | %s |\n",
			escapeCell(q.ID),
			escapeCell(q.Body),
			escapeCell(q.Owner),
		)
	}
	return nil
}

// generatedBannerBacklog is the DO-NOT-EDIT banner for backlog.md.
const generatedBannerBacklog = `<!--
  GENERATED by ` + "`registry gen`" + ` (tools/registry) — DO NOT EDIT BY HAND.
  Source of truth: registry/priority.yaml + registry/items.yaml
  Regenerate:      make registry
  Validated in CI by the ` + "`registry-sync`" + ` job. Hand edits FAIL CI.
-->
`

// computeGates returns, per item id, the backlog "gate" cell — who is holding
// the item, computed from status + the dependency DAG:
//
//	ready           all deps satisfied + not started + owner:agent → pullable now
//	👤 pete         all deps satisfied but owner:pete → held by Pete, NOT agent-
//	                pullable (`registry ready` excludes owner:pete); the owner
//	                column shows the same, but the gate must not read "ready"
//	🛠 in-progress  status IN_PROGRESS → already being worked (a live thread)
//	🔒 q31[, q24]   transitively rooted in an open question → BLOCKED ON PETE;
//	                the listed qN(s) are exactly the answers that unblock it
//	⏳ i122b        blocked only on other open WORK (no question at the root) →
//	                unblocks itself as the queue drains
//
// "ready" and the 🔒 state are mutually exclusive: a ready item has all direct
// deps satisfied (DONE/WONTFIX), and a DONE item cannot depend on an open
// question, so a ready item never transitively reaches one.
func computeGates(reg *Registry) map[string]string {
	itemStatus := map[string]Status{}
	for _, it := range reg.Items {
		itemStatus[it.ID] = it.Status
	}
	questionIDs := map[string]bool{}
	for _, q := range reg.Questions {
		questionIDs[q.ID] = true
	}

	// depSatisfied mirrors runReady: an open question is unsatisfied; a DONE or
	// WONTFIX item is satisfied; a missing target is treated as satisfied (stale
	// edge); any other (open/in-progress) item is unsatisfied.
	depSatisfied := func(dep string) bool {
		if questionIDs[dep] {
			return false
		}
		st, ok := itemStatus[dep]
		if !ok {
			return true
		}
		return st == StatusDone || st == StatusWontfix
	}

	// rootQuestions[item] = the set of open questions this item is transitively
	// rooted in (reverse reachability over depends_on, starting from each open
	// question and walking to its dependents).
	rev := buildReverseEdges(reg.Items)
	rootQuestions := map[string]map[string]bool{}
	for _, q := range reg.Questions {
		var queue []string
		queue = append(queue, rev[q.ID]...)
		visited := map[string]bool{}
		for len(queue) > 0 {
			x := queue[0]
			queue = queue[1:]
			if visited[x] {
				continue
			}
			visited[x] = true
			if rootQuestions[x] == nil {
				rootQuestions[x] = map[string]bool{}
			}
			rootQuestions[x][q.ID] = true
			queue = append(queue, rev[x]...)
		}
	}

	gates := map[string]string{}
	for _, it := range reg.Items {
		if it.Status == StatusInProgress {
			gates[it.ID] = "🛠 in-progress"
			continue
		}
		var unsat []string
		for _, dep := range it.DependsOn {
			if !depSatisfied(dep) {
				unsat = append(unsat, dep)
			}
		}
		if len(unsat) == 0 {
			// All deps satisfied. An owner:pete item is still NOT agent-pullable
			// (`registry ready` excludes owner:pete), so it must not read "ready"
			// — show who holds it instead. Mirrors the ready filter exactly.
			if it.Owner == "pete" {
				gates[it.ID] = "👤 pete"
			} else {
				gates[it.ID] = "ready"
			}
			continue
		}
		if qs := rootQuestions[it.ID]; len(qs) > 0 {
			keys := make([]string, 0, len(qs))
			for q := range qs {
				keys = append(keys, q)
			}
			sortStrings(keys)
			gates[it.ID] = "🔒 " + strings.Join(keys, ", ")
			continue
		}
		gates[it.ID] = "⏳ " + strings.Join(unsat, ", ")
	}
	return gates
}

// genBacklog writes the priority-ordered backlog view to w. The table lists all
// pullable items in priority order. The "gate" column shows who is holding each
// item (see computeGates). There is no rank column — the row order IS the
// priority, and a stable id key keeps diffs small when items move. When priority
// is empty the table is written with zero data rows (header only).
func genBacklog(reg *Registry, priority []string, w io.Writer) error {
	// Build a map from item id to item for fast lookup.
	byID := map[string]Item{}
	for _, it := range reg.Items {
		byID[it.ID] = it
	}

	reverseEdges := buildReverseEdges(reg.Items)
	gates := computeGates(reg)

	// In-file anchor targets (i159): only ids that actually render a row in this
	// backlog view (priority ids present in the registry) are linked, so a
	// linkified ref never dangles.
	var backlogIDs []string
	for _, id := range priority {
		if _, ok := byID[id]; ok {
			backlogIDs = append(backlogIDs, id)
		}
	}
	backlogPresent := presentIDs(backlogIDs)

	header := "| **id** | item | status | owner | gate | deps | dependents |\n|---|---|---|---|---|---|---|\n"

	fmt.Fprint(w, generatedBannerBacklog)
	fmt.Fprint(w, "\n")
	fmt.Fprint(w, header)
	for _, id := range priority {
		it, ok := byID[id]
		if !ok {
			// Omit unknown ids from the view (validate would have caught them).
			continue
		}
		fmt.Fprintf(w, "| %s | %s | %s | %s | %s | %s | %s |\n",
			renderIDCell(it.ID),
			renderItemCell(it),
			escapeCell(renderItemStatus(it)),
			escapeCell(it.Owner),
			escapeCell(gates[it.ID]),
			linkifyIDList(escapeCell(renderItemDeps(it)), backlogPresent),
			linkifyIDList(escapeCell(renderItemDependents(it, reverseEdges)), backlogPresent),
		)
	}
	return nil
}
