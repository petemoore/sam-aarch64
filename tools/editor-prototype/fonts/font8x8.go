// Font8x8 returns the vendored 8×8 font as a samscreen.Font. Glyphs above
// 0x7F render blank (the basic-latin block covers the editor's repertoire;
// box-drawing/arrow markers can be added to the table when a styled variant
// earns them — spec §2.1).
func Font8x8() (samscreen.Font, error) {
	glyphs := make([][]uint8, 256)
	for ch := 0; ch < 128; ch++ {
		rows := make([]uint8, 8)
		copy(rows, font8x8Basic[ch][:])
		glyphs[ch] = rows
	}
	for ch := 128; ch < 256; ch++ {
		glyphs[ch] = make([]uint8, 8)
	}
	f, err := samscreen.NewBitmapFont(8, 8, glyphs)
	if err != nil {
		return nil, fmt.Errorf("font8x8: %w", err)
	}
	return f, nil
}
